import { createHash } from 'node:crypto';
import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { format, resolveConfig } from 'prettier';
import sharp from 'sharp';

// Optimize retained ImageGen edits. This script never invokes generation or edits
// supplied originals; semantic editing prompts and provenance live in the manifest.
const manifestPath = 'source-assets/about/manifest.json';
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
await mkdir(manifest.outputs.directory, { recursive: true });

async function describe(path) {
  const [metadata, file, contents] = await Promise.all([
    sharp(path).metadata(),
    stat(path),
    readFile(path),
  ]);
  return {
    path,
    width: metadata.width,
    height: metadata.height,
    bytes: file.size,
    sha256: createHash('sha256').update(contents).digest('hex'),
  };
}

async function variants(image, crop) {
  const metadata = await sharp(image.editedSource).metadata();
  // Explicit portrait crops keep screen and architectural detail sharp on mobile.
  if (
    crop &&
    (crop.left < 0 ||
      crop.top < 0 ||
      crop.left + crop.width > metadata.width ||
      crop.top + crop.height > metadata.height)
  ) {
    throw new Error(
      `Mobile crop extends outside the retained ${image.key} edit.`,
    );
  }
  const width = crop?.width ?? metadata.width;
  const height = crop?.height ?? metadata.height;
  const requested = crop
    ? manifest.outputs.mobileWidths
    : manifest.outputs.requestedWidths;
  const widths = [
    ...new Set([...requested.filter((size) => size <= width), width]),
  ];
  const name = `${image.key}${crop ? '-mobile' : ''}`;
  const outputs = [];
  for (const size of widths) {
    for (const [format, settings] of Object.entries(manifest.outputs.formats)) {
      const path = `${manifest.outputs.directory}/${name}-${size}.${format}`;
      let pipeline = sharp(image.editedSource);
      if (crop) pipeline = pipeline.extract(crop);
      await pipeline
        .resize({ width: size, withoutEnlargement: true })
        .toFormat(format, settings)
        .toFile(path);
      outputs.push(await describe(path));
    }
  }
  return {
    media: { base: `/images/about/${name}`, widths, width, height },
    outputs,
  };
}

const media = {};
for (const image of manifest.images) {
  image.original = await describe(image.source);
  image.edited = await describe(image.editedSource);
  const desktop = await variants(image);
  const mobile = image.mobile ? await variants(image, image.mobile.crop) : null;
  image.optimized = [...desktop.outputs, ...(mobile?.outputs ?? [])];
  media[image.key] = {
    ...desktop.media,
    ...(mobile ? { mobile: mobile.media } : {}),
    caption: image.caption,
    alt: image.alt,
  };
}

await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);
const mediaPath = 'src/data/about-media.ts';
const mediaSource =
  `// Generated by scripts/prepare-about-assets.mjs from retained illustrative artwork.\n` +
  `type AboutImageSource = {\n` +
  `  base: string;\n` +
  `  widths: readonly number[];\n` +
  `  width: number;\n` +
  `  height: number;\n` +
  `};\n` +
  `type AboutMedia = AboutImageSource & {\n` +
  `  mobile?: AboutImageSource;\n` +
  `  caption: string;\n` +
  `  alt: '';\n` +
  `};\n\n` +
  `export const aboutMedia = ${JSON.stringify(media, null, 2)} as const satisfies Record<\n` +
  `  'hero' | 'workspace' | 'philosophy',\n` +
  `  AboutMedia\n` +
  `>;\n`;
await writeFile(
  mediaPath,
  await format(mediaSource, {
    ...(await resolveConfig(mediaPath)),
    parser: 'typescript',
  }),
);
console.log(
  JSON.stringify({
    images: manifest.images.map((image) => ({
      key: image.key,
      original: image.original,
      edited: image.edited,
      variants: image.optimized.length,
      largestBytes: Math.max(...image.optimized.map((output) => output.bytes)),
    })),
  }),
);
